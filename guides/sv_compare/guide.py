def sv_gibbs(y, nsim, burnin, pr, rng):
    """the Gibbs sampler of guides/sv_gibbs, returning the parameter draws and the posterior mean
    of h"""
    T = y.size
    offset = 1e-4
    mu0, Vmu, muh0, Vmuh = pr.mu0, pr.Vmu, pr.muh0, pr.Vmuh
    phi0, Vphi, nuh, Sh = pr.phi0, pr.Vphi, pr.nuh, pr.Sh
    hyp = dict(nuh=nuh, Sh=Sh, phi0=phi0, Vphi=Vphi, mu0=muh0, Vmu=Vmuh)
    muh, phi, sig2h = np.log(y.var(ddof=1)), .98, .04   # starting values
    h = muh * np.ones(T)
    store_theta = np.zeros((nsim, 4))
    hbar = np.zeros(T)
    for isim in range(burnin + nsim):
        Kmu = 1 / Vmu + np.sum(np.exp(-h))              # K_mu = 1/V_mu + sum_t e^{-h_t}
        mu = (mu0 / Vmu + np.exp(-h) @ y) / Kmu + rng.standard_normal() / np.sqrt(Kmu)

        ystar = np.log((y - mu)**2 + offset)            # s, then h: guides/sv_states
        h, _ = ssm.ksc_ar1_mean(ystar, h, muh, phi, sig2h, rng=rng)

        [muh], [phi], [sig2h], _ = ssm.sv_params(h, muh, phi, hyp, 1, rng=rng)   # guides/sv_gibbs

        if isim >= burnin:
            store_theta[isim - burnin] = mu, muh, phi, sig2h
            hbar = hbar + h / nsim
    return store_theta, hbar


def svt_gibbs(y, nsim, burnin, pr, rng):
    """the Gibbs sampler of guides/sv_t, returning the parameter draws and the posterior mean of
    h"""
    T = y.size
    offset = 1e-4
    mu0, Vmu, muh0, Vmuh = pr.mu0, pr.Vmu, pr.muh0, pr.Vmuh
    phi0, Vphi, nuh, Sh, nuub = pr.phi0, pr.Vphi, pr.nuh, pr.Sh, pr.nuub
    hyp = dict(nuh=nuh, Sh=Sh, phi0=phi0, Vphi=Vphi, mu0=muh0, Vmu=Vmuh)
    muh, phi, sig2h, nu = np.log(y.var(ddof=1)), .98, .04, 5.0   # starting values
    h = muh * np.ones(T)
    lam = np.ones(T)
    store_theta = np.zeros((nsim, 5))
    hbar = np.zeros(T)
    for isim in range(burnin + nsim):
        w = 1 / (lam * np.exp(h))                   # 1/(lambda_t e^{h_t})
        Kmu = 1 / Vmu + np.sum(w)                   # K_mu = 1/V_mu + sum_t 1/(lambda_t e^{h_t})
        mu = (mu0 / Vmu + w @ y) / Kmu + rng.standard_normal() / np.sqrt(Kmu)

        ystar = np.log((y - mu)**2 / lam + offset)      # y*_t = log((y_t - mu)^2/lambda_t + c)
        h, _ = ssm.ksc_ar1_mean(ystar, h, muh, phi, sig2h, rng=rng)

        e2 = (y - mu)**2 * np.exp(-h)                   # lambda_t ~ IG((nu + 1)/2, (nu + e2_t)/2)
        lam = 1 / rng.gamma((nu + 1) / 2, 2 / (nu + e2))

        nu, _, _ = ssm.nu_studentt(lam, nu, nuub, rng=rng)

        [muh], [phi], [sig2h], _ = ssm.sv_params(h, muh, phi, hyp, 1, rng=rng)   # guides/sv_gibbs

        if isim >= burnin:
            store_theta[isim - burnin] = mu, muh, phi, sig2h, nu
            hbar = hbar + h / nsim
    return store_theta, hbar


def cv_posterior(y, pr, nsim, rng):
    """The constant variance, y_t ~ N(mu, e^{mu_h}): mu integrated out in closed form, then mu_h
    by the trapezoid rule on 2e4 points over 12 posterior standard deviations on either side of
    the mode. Returns log p(y), nsim exact draws of (mu, mu_h), and, as a check, the log of the
    ratio of the integral by adaptive quadrature on the same interval to the trapezoid one."""
    ngrid = 20000
    T = y.size
    V = pr.Vmu
    yc = y - pr.mu0
    a, b = yc @ yc, np.sum(yc)

    def lpy(s):
        """log p(y | mu_h) = log N(y; mu0 1, s I + V 1 1'), s = e^{mu_h}"""
        return (-T / 2 * np.log(2 * np.pi) - .5 * (T * np.log(s) + np.log(1 + V * T / s))
                - (a - V * b**2 / (s + V * T)) / (2 * s))

    def lf(m):
        return lpy(np.exp(m)) - .5 * np.log(2 * np.pi * pr.Vmuh) - .5 * (m - pr.muh0)**2 / pr.Vmuh

    mhat = minimize_scalar(lambda m: -lf(m), bounds=(-20, 20), method='bounded',
                           options={'xatol': 1e-10}).x
    sd = np.sqrt(2 / T)                                 # about the posterior sd of mu_h
    g = np.linspace(mhat - 12 * sd, mhat + 12 * sd, ngrid)
    f = lf(g)
    fmax = f.max()
    lml = fmax + np.log(trapezoid(np.exp(f - fmax), g))
    lratio = (np.log(quad(lambda m: np.exp(lf(m) - fmax), g[0], g[-1], epsabs=0,
                          epsrel=1e-12)[0])
              - np.log(trapezoid(np.exp(f - fmax), g)))
    cdf = cumulative_trapezoid(np.exp(f - fmax), g, initial=0)
    cdf = cdf / cdf[-1]
    cu, iu = np.unique(cdf, return_index=True)
    muh = np.interp(rng.random(nsim), cu, g[iu])        # mu_h by the inverse cdf
    s = np.exp(muh)
    Kmu = 1 / V + T / s                                 # mu given mu_h: K_mu = 1/V_mu + T/e^{mu_h}
    mu = (pr.mu0 / V + np.sum(y) / s) / Kmu + rng.standard_normal(nsim) / np.sqrt(Kmu)
    return lml, np.column_stack([mu, muh]), lratio


def is_logml(lp, draws, R, rng):
    """log p(y) by importance sampling, as in guides/tvp_compare: a t density with 5 degrees of
    freedom at the mean and covariance of the posterior draws, the cross-entropy fit of a normal
    density (Chan and Eisenstat, 2015), with heavier tails. lml is the log of the mean of all R
    weights; nse comes from 20 batches."""
    nu = 5
    d = draws.shape[1]
    m = draws.mean(axis=0)
    C = np.linalg.cholesky(np.cov(draws, rowvar=False))
    z = rng.standard_normal((d, R)) / np.sqrt(rng.chisquare(nu, R) / nu)
    phi = m[:, None] + C @ z
    lconst = (gammaln((nu + d) / 2) - gammaln(nu / 2) - d / 2 * np.log(nu * np.pi)
              - np.sum(np.log(np.diag(C))))
    logw = np.zeros(R)
    for r in range(R):                                  # log p(y, theta) - log g(phi)
        logw[r] = lp(phi[:, r]) - (lconst - (nu + d) / 2 * np.log(1 + z[:, r] @ z[:, r] / nu))
    lml = logmeanexp(logw)
    lb = np.array([logmeanexp(wb) for wb in logw.reshape(20, R // 20)])
    nse = lb.std(ddof=1) / np.sqrt(20)
    return lml, nse


def prior_is(s2, muh, phi, sig2h, nu, N, nb, rng):
    """log p(y | theta) by importance sampling from the prior of h: nb batches of N paths, each
    weighted by the likelihood. nu = inf gives normal errors, otherwise Student-t errors."""
    T = s2.size
    lb = np.zeros(nb)
    lw_all = np.zeros((N, nb))
    for b in range(nb):
        h = np.zeros((T, N))
        h[0] = muh + np.sqrt(sig2h / (1 - phi**2)) * rng.standard_normal(N)
        for t in range(1, T):
            h[t] = muh + phi * (h[t - 1] - muh) + np.sqrt(sig2h) * rng.standard_normal(N)
        if np.isinf(nu):
            lw = np.sum(-.5 * np.log(2 * np.pi) - .5 * h - .5 * s2[:, None] * np.exp(-h), axis=0)
        else:
            lw = np.sum(gammaln((nu + 1) / 2) - gammaln(nu / 2) - .5 * np.log(nu * np.pi) - .5 * h
                        - (nu + 1) / 2 * np.log(1 + s2[:, None] * np.exp(-h) / nu), axis=0)
        lw_all[:, b] = lw
        lb[b] = logmeanexp(lw)
    lml = logmeanexp(lw_all.ravel())
    se = lb.std(ddof=1) / np.sqrt(nb)
    return lml, se


def logmeanexp(x):
    """log(mean(exp(x))), computed without overflow"""
    mx = np.max(x)
    return mx + np.log(np.mean(np.exp(x - mx)))


