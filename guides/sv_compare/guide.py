def lnorm(x, m, V):
    """log N(x; m, V)"""
    return -.5 * np.log(2 * np.pi * V) - .5 * (x - m)**2 / V


def lig(x, nu, S):
    """log IG(x; nu, S)"""
    return nu * np.log(S) - gammaln(nu) - (nu + 1) * np.log(x) - S / x


cphi = np.log(ndtr((1 - pr.phi0) / np.sqrt(pr.Vphi)) - ndtr((-1 - pr.phi0) / np.sqrt(pr.Vphi)))


def lprior(mu, muh, phi, sig2h):
    """the log prior density of (mu, mu_h, phi, sigma_h^2), with phi ~ TN on (-1, 1)"""
    return (lnorm(mu, pr.mu0, pr.Vmu) + lnorm(muh, pr.muh0, pr.Vmuh)
            + lnorm(phi, pr.phi0, pr.Vphi) - cphi + lig(sig2h, pr.nuh, pr.Sh))


def nuof(z):
    """nu = 2 + (nuub - 2)/(1 + e^{-z})"""
    return 2 + (pr.nuub - 2) / (1 + np.exp(-z))


def ljnu(nu):
    """log dnu/dz"""
    return np.log((nu - 2) * (pr.nuub - nu) / (pr.nuub - 2))


